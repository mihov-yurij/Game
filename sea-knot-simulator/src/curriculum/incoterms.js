export function lotBasisLine(lot) {
  if (lot.incoterm === 'FOB') {
    return `Базис: FOB ${lot.namedPlace}. Поставка была в порту отгрузки, к нам судно пришло на выгрузку.`
  }
  if (lot.incoterm === 'CIF') {
    return `Базис: CIF ${lot.namedPlace}. Наш порт — порт назначения.`
  }
  return `Базис: DAP ${lot.namedPlace}. Названное место — наш терминал.`
}

