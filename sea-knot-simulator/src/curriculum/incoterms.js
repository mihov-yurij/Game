export function questionById(id) {
  return QUESTIONS.find((question) => question.id === id) ?? null
}

export function repairQuestionId({ isCraneBroken, shipStatus, demurrageReason, incoterm }) {
  const craneCrisis = isCraneBroken
    || shipStatus === 'Unloading'
    || (shipStatus === 'Demurrage' && demurrageReason === 'crane')
  if (craneCrisis) return 'h-app-during'
  if (incoterm === 'DAP') return 'h-app-dap'
  return 'h-app-before'
}
